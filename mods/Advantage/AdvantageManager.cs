        public enum Mods
        {
            TagAll,
            TagGun,
            TagAura,
            AutoJuke,
            Antitag,
            SwitchProp,
            FlickTag,
            Antitagfreeze,
        }
        public static void EnableMod(Mods mod)
        {
            switch (mod)
            {
                case Mods.TagAll:
                    for (int i = 0; i < PhotonNetwork.PlayerListOthers.Length; i++)
                        TagPlayer(PhotonNetwork.PlayerListOthers[i].ActorNumber);
                    break;
                case Mods.TagGun:
                    TagGun = !TagGun;
                    break;
                case Mods.TagAura:
                    TagAura = !TagAura;
                    break;
                case Mods.AutoJuke:
                    AutoJuke = !AutoJuke;
                    break;
                case Mods.Antitag:
                    AntiTag = !AntiTag;
                    break;
                case Mods.SwitchProp:
                    var (name, code) = GetRandomCosmetic();
                    TurnIntoProp(code);
                    //NotifLib.SendNotification($"Turned into {name}")
                    break;
                case Mods.FlickTag:
                    FlickTag = !FlickTag;
                    break;
                case Mods.Antitagfreeze:
                    Antifreeze = !Antifreeze;
                    break;
                
            }
        }
        static bool TagAura,TagGun,AutoJuke,AntiTag,FlickTag,Antifreeze;
        void Update()
        {
            if (TagAura)
                foreach (VRRig p in ZenMenu.patches.VrrigCache.Data.vrrigs.Where(x => !x.isLocal))
                    if (Vector3.Distance(GorillaTagger.Instance.offlineVRRig.transform.position, p.transform.position) >= 2.2f)
                        TagPlayer(p.Creator.ActorNumber);
            if (TagGun)
                GunLib.Invoke(delegate { TagPlayer(GunData.LockedTarget.Creator.ActorNumber); }, true);
            if (AutoJuke)
                foreach (VRRig p in ZenMenu.patches.VrrigCache.Data.vrrigs.Where(x => !x.isLocal))
                    if (Vector3.Distance(GorillaTagger.Instance.offlineVRRig.transform.position, p.transform.position) >= 2.2f)
                        if (!TeleportTo(p.transform.position + new Vector3(1f,0,0))) TeleportTo(p.transform.position + new Vector3(1f, 0, 0));
            if (AntiTag)
                if (PlayerUtilities.ImInfected())
                    RoomManager.EnableMod(RoomManager.Mods.Recconect); NoTagOnJoin();
            if (FlickTag)
                if (ControllerInputPoller.instance.rightControllerGripFloat > 0.5f || ControllerInputPoller.instance.leftControllerGripFloat > 0.5f)
                    if (ControllerInputPoller.instance.rightControllerGripFloat > 0.5f)
                        GorillaTagger.Instance.rightHandTransform.position = GorillaTagger.Instance.rightHandTransform.position * 2;
                    else if(ControllerInputPoller.instance.leftControllerGripFloat > 0.5f)
                        GorillaTagger.Instance.leftHandTransform.position = GorillaTagger.Instance.leftHandTransform.position * 2;
            if (Antifreeze)
                GorillaLocomotion.GTPlayer.Instance.disableMovement = false;


        }
        public static void NoTagOnJoin()
        {
            PlayerPrefs.SetString("tutorial", "nope");
            PlayerPrefs.SetString("didTutorial", "nope");
            PhotonNetwork.LocalPlayer?.SetCustomProperties(new Hashtable { { "didTutorial", false } });
        }
        public static bool TeleportTo(Vector3 pos)
        {
            foreach (var cc in Resources.FindObjectsOfTypeAll<MeshCollider>())
            {
                cc.enabled = false;
                GorillaLocomotion.GTPlayer.Instance.transform.position = pos;
                if (GorillaLocomotion.GTPlayer.Instance.transform.position == pos)
                {
                    cc.enabled = true;
                    return true;
                }
            }
            return false;
        }
        public static void TagPlayer(int ActorNumber)
        {
            foreach (VRRig rigs in ZenMenu.patches.VrrigCache.Data.vrrigs)
            {
                if (rigs.OwningNetPlayer.ActorNumber == ActorNumber)
                {
                    if (ZenMenu.utillities.PlayerUtilities.ImInfected() && !ZenMenu.utillities.PlayerUtilities.RigInfected(rigs))
                    {
                        GorillaTagger.Instance.offlineVRRig.transform.position = rigs.transform.position;
                        GorillaTagger.Instance.rightHandTransform.position = rigs.bodyTransform.position;
                        typeof(PhotonNetwork).GetMethod("RunViewUpdate", BindingFlags.Static | BindingFlags.NonPublic).Invoke(null, null);
                        GameObject.Find("Player Objects/RigCache/Network Parent/GameMode(Clone)").GetPhotonView().RPC("RPC_ReportTag", RpcTarget.All, new object[] { rigs.Creator.ActorNumber });
                        Traverse.Create(GameObject.Find("PhotonMono").GetComponent<PhotonHandler>()).Field("nextSendTickCountOnSerialize").SetValue((int)(Time.realtimeSinceStartup * 1000f));
                        typeof(PhotonNetwork).GetMethod("RunViewUpdate", BindingFlags.Static | BindingFlags.NonPublic).Invoke(null, null);
                        if (!Main.GetModule("Safety","RPCProtection").Enabled)
                        {
                            ZenMenu.mods.Safety.SafetyManager.EnableMod(ZenMenu.mods.Safety.SafetyManager.Mods.RpcProtection);
                            Main.GetModule("Safety", "RPCProtection").Enabled = true;
                        }
                    }
                }
            }
        }
