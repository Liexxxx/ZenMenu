        public static void TurnIntoProp(string playfabId)
        {
            PropHuntPools.TryGetGrabbableProp(playfabId, out PropHuntGrabbableProp grabbableProp);
            PropHuntPools.TryGetTaggableProp(playfabId, out PropHuntTaggableProp taggbleprop);
            if (grabbableProp == null) return;
            PropHuntHandFollower follower = VRRig.LocalRig.propHuntHandFollower;
            VRRig.LocalRig.propHuntHandFollower.DestroyProp();
            FetchField(typeof(PropHuntHandFollower), "_grabbableProp").SetValue(VRRig.LocalRig.propHuntHandFollower,grabbableProp);
            FetchField(typeof(PropHuntHandFollower), "_taggableProp").SetValue(VRRig.LocalRig.propHuntHandFollower, taggbleprop);
            FetchField(typeof(PropHuntHandFollower), "_prop").SetValue(VRRig.LocalRig.propHuntHandFollower, grabbableProp.gameObject);
            FetchField(typeof(PropHuntHandFollower), "_propOffset").SetValue(VRRig.LocalRig.propHuntHandFollower, grabbableProp.offset);
            grabbableProp.handFollower = follower;
            FetchField(typeof(PropHuntHandFollower), "hasProp").SetValue(VRRig.LocalRig.propHuntHandFollower, true);
            for (int i = 0; i < grabbableProp.interactionPoints.Count; i++)
                grabbableProp.interactionPoints[i].OnSpawn(VRRig.LocalRig);
        }
